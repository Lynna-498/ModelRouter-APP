        case stringList                   // 字符串数组：行内标签增删（与 input_modalities 同族呈现，无预置选项）
        case structure                    // 对象：主界面行内层级展开（子参数退一格，按形态给控件）
        case structureList                // 对象数组：行内递归展开（元素 [i] 分组）
