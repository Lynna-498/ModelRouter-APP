    let key: String
    let zh: String
    let group: String
    let desc: String
    let inferred: Bool
    let control: Control
    /// 「填写：」说明（visibility 为官方示例样式，51 条全量）
    let howTo: String
    /// 现行读取状态：active＝现行读取可写 / ignored＝现行版本忽略 / localOnly＝官方 catalog 无此字段
    let status: ParamStatus
    /// R23 用户增补：条目挂靠的父路径（nil/空＝条目顶层；如 "model_messages"＝其内部子键）。
    /// 内置条目恒 nil——内置复杂结构的子键经 MetaKnownShapes 认识，无需此位。
    var parentPath: String? = nil

    var id: String { key }
}

