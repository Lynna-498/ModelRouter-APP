import Foundation


// MARK: - 目录生成（model_modelrouter.json；slug=display_name=模型名称，字面直用）
public enum CodexCatalog {
    /// 推理档位（结构化行编辑的数据形态；枚举 none/minimal/low/medium/high/xhigh/max——max 为 DeepSeek 官方元数据实有档）
    public struct ReasoningTier {
        public var effort: String
        public var description: String
        public init(effort: String, description: String) {
            self.effort = effort
            self.description = description
        }
    }

    /// 最小可用条目：字段集对齐 Codex 认识的官方 models.json 结构（与模型管理既有生成器同源）。
    public static func minimalEntry(slug: String, displayName: String, contextWindow: Int = 262144,
                                    imageInput: Bool = false,
                                    tiers: [ReasoningTier] = [], defaultTier: String? = nil) -> [String: Any] {
        var e: [String: Any] = [
            "slug": slug,
            "display_name": displayName,
            "description": "Minimal metadata generated by ModelRouter for \(slug)",
            "context_window": contextWindow,
            "effective_context_window_percent": 95,
            "supports_parallel_tool_calls": false,
            "input_modalities": imageInput ? ["text", "image"] : ["text"],
            "shell_type": "default",
            "visibility": "list",
            "supported_in_api": true,
            "priority": 1,
            "base_instructions": "",
            "support_verbosity": false,
            "supports_reasoning_summaries": false,
            "experimental_supported_tools": [Any](),
            "truncation_policy": ["mode": "bytes", "limit": 10000],
        ]
        if imageInput { e["supports_image_detail_original"] = true }
        let ordered = tiers.filter { !$0.effort.isEmpty }
        if !ordered.isEmpty {
            if let d = defaultTier, !d.isEmpty { e["default_reasoning_level"] = d }
            e["supported_reasoning_levels"] = ordered.map { ["effort": $0.effort, "description": $0.description] }
        }
        return e
    }

    /// 按名称级口径生成目录条目：有存储元数据则以之为底、slug/display_name 强制覆写为模型名称；
    /// 无存储元数据或存储内容损坏 → 最小模板。
    public static func entry(name: String, metaJSON: String?) -> [String: Any] {
        if let raw = metaJSON,
           let data = raw.data(using: .utf8),
           let obj = try? JSONSerialization.jsonObject(with: data, options: []),
           var dict = obj as? [String: Any] {
            dict["slug"] = name
            dict["display_name"] = name
            return dict
        }
        return minimalEntry(slug: name, displayName: name)
    }

    /// 生成整个目录：{"models":[…]}，条目顺序＝添加的模型顺序。
    public static func generate(added: [String], metaJSON: (String) -> String?) -> [String: Any] {
        ["models": added.map { entry(name: $0, metaJSON: metaJSON($0)) }]
    }

    /// 生成目录的 pretty 文本（B 窗预览用；与落盘同构）。
    public static func prettyText(added: [String], metaJSON: (String) -> String?) -> String {
        let obj = generate(added: added, metaJSON: metaJSON)
        guard let d = try? JSONSerialization.data(withJSONObject: obj, options: [.prettyPrinted, .sortedKeys]),
              let s = String(data: d, encoding: .utf8) else { return "" }
        return s
    }

    /// 从目录 JSON 文本解析 slug 列表（B 窗保存键的目录脏判定基线：表没变不改文件）。
    /// 文件缺失/不可解析 → nil（视为无目录文件）。
    public static func slugs(inJSON text: String) -> [String]? {
        guard let data = text.data(using: .utf8),
              let obj = try? JSONSerialization.jsonObject(with: data, options: []) as? [String: Any],
              let models = obj["models"] as? [Any] else { return nil }
        return models.compactMap { ($0 as? [String: Any])?["slug"] as? String }
    }
}
